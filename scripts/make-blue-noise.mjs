/**
 * Writes components/landing/blue-noise.ts: a 64x64 blue-noise threshold
 * tile for the sphere shading's dither (components/landing/sphere-shading.tsx).
 *
 * Void-and-cluster (Ulichney 1993) on a torus, so the tile repeats without
 * a seam. Each cell gets a rank 0..4095; the tile stores it as a byte
 * (rank >> 4). Seeded, so the output is the same on every run.
 *
 *   node scripts/make-blue-noise.mjs
 */
import { writeFileSync } from "node:fs";

const N = 64;
const AREA = N * N;
const SIGMA = 1.5;

let seed = 0x5ad0;
function random() {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

// Gaussian weight by toroidal offset.
const kernel = new Float64Array(AREA);
for (let y = 0; y < N; y += 1) {
  for (let x = 0; x < N; x += 1) {
    const dx = Math.min(x, N - x);
    const dy = Math.min(y, N - y);
    kernel[y * N + x] = Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA));
  }
}

function makeField(bits) {
  const energy = new Float64Array(AREA);
  const toggle = (index, sign) => {
    const px = index % N;
    const py = (index / N) | 0;
    for (let y = 0; y < N; y += 1) {
      const ky = ((y - py + N) % N) * N;
      for (let x = 0; x < N; x += 1) energy[y * N + x] += sign * kernel[ky + ((x - px + N) % N)];
    }
  };
  for (let i = 0; i < AREA; i += 1) if (bits[i]) toggle(i, 1);
  return { energy, toggle };
}

function extreme(bits, energy, want, pickMax) {
  let best = -1;
  let value = pickMax ? -Infinity : Infinity;
  for (let i = 0; i < AREA; i += 1) {
    if (bits[i] !== want) continue;
    if (pickMax ? energy[i] > value : energy[i] < value) {
      value = energy[i];
      best = i;
    }
  }
  return best;
}

// 1. Initial pattern: 10% random points, relaxed by moving the tightest
//    cluster into the largest void until the move undoes itself.
const initial = new Uint8Array(AREA);
let ones = 0;
while (ones < AREA / 10) {
  const i = Math.floor(random() * AREA);
  if (!initial[i]) {
    initial[i] = 1;
    ones += 1;
  }
}
{
  const { energy, toggle } = makeField(initial);
  for (;;) {
    const cluster = extreme(initial, energy, 1, true);
    initial[cluster] = 0;
    toggle(cluster, -1);
    const void_ = extreme(initial, energy, 0, false);
    initial[void_] = 1;
    toggle(void_, 1);
    if (void_ === cluster) break;
  }
}

const rank = new Int32Array(AREA);

// 2. Rank the initial points by removing the tightest cluster each time.
{
  const bits = initial.slice();
  const { energy, toggle } = makeField(bits);
  for (let r = ones - 1; r >= 0; r -= 1) {
    const cluster = extreme(bits, energy, 1, true);
    bits[cluster] = 0;
    toggle(cluster, -1);
    rank[cluster] = r;
  }
}

// 3. Rank the rest by filling the largest void each time. Past half full
//    this is the same as taking the tightest cluster of zeros.
{
  const bits = initial.slice();
  const { energy, toggle } = makeField(bits);
  for (let r = ones; r < AREA; r += 1) {
    const void_ = extreme(bits, energy, 0, false);
    bits[void_] = 1;
    toggle(void_, 1);
    rank[void_] = r;
  }
}

const bytes = Buffer.from(Array.from(rank, (r) => r >> 4));
const source = `// Generated by scripts/make-blue-noise.mjs; do not edit by hand.
// A ${N}x${N} blue-noise threshold tile, one byte per cell, row-major.

export const BLUE_NOISE_SIZE = ${N};

const ENCODED =
  "${bytes.toString("base64")}";

function decode(text: string) {
  const binary = atob(text);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) out[i] = binary.charCodeAt(i);
  return out;
}

let tile: Uint8Array | null = null;

/** The tile, decoded on first use (atob is browser-only at module scope). */
export function blueNoise(): Uint8Array {
  tile ??= decode(ENCODED);
  return tile;
}
`;
writeFileSync(new URL("../components/landing/blue-noise.ts", import.meta.url), source);
console.log(`wrote ${N}x${N} tile`);
